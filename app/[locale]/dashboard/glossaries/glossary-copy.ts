export type GlossaryCopy = (typeof glossaryCopy)[GlossaryLocale];

export function resolveGlossaryLocale(locale: string): GlossaryLocale {
  return locale === "vi" || locale === "ja" ? locale : "en";
}

const languageLabels = {
  vi: {vn: "Tiếng Việt", en: "Tiếng Anh", jp: "Tiếng Nhật"},
  en: {vn: "Vietnamese", en: "English", jp: "Japanese"},
  ja: {vn: "ベトナム語", en: "英語", jp: "日本語"},
} as const;

const languageFlags = {
  vn: "https://cdnjs.cloudflare.com/ajax/libs/twemoji/14.0.2/svg/1f1fb-1f1f3.svg",
  en: "https://cdnjs.cloudflare.com/ajax/libs/twemoji/14.0.2/svg/1f1ec-1f1e7.svg",
  jp: "https://cdnjs.cloudflare.com/ajax/libs/twemoji/14.0.2/svg/1f1ef-1f1f5.svg",
} as const;

export function normalizeGlossaryLanguage(code: string): keyof typeof languageLabels.vi | null {
  const normalized = code.trim().toLowerCase();

  if (normalized === "vi" || normalized === "vn" || normalized === "vietnamese") return "vn";
  if (normalized === "ja" || normalized === "jp" || normalized === "japanese") return "jp";
  if (normalized === "en" || normalized === "english") return "en";

  return null;
}

export function getGlossaryLanguageLabel(code: string, locale: GlossaryLocale): string {
  const normalized = normalizeGlossaryLanguage(code);
  return normalized ? languageLabels[locale][normalized] : code;
}

export function getGlossaryLanguageFlag(code: string): string {
  const normalized = normalizeGlossaryLanguage(code) ?? "en";
  return languageFlags[normalized];
}

export function getGlossaryLanguageTag(code: string): string {
  const normalized = normalizeGlossaryLanguage(code);
  return normalized === "vn" ? "VI" : normalized === "jp" ? "JA" : normalized === "en" ? "EN" : code.slice(0, 2).toUpperCase();
}
